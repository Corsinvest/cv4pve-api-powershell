<#
.SYNOPSIS
Generates the cmdlet reference of the documentation site from the module source.

.DESCRIPTION
Reads Corsinvest.ProxmoxVE.Api.psm1 with the PowerShell parser (the module is not imported, so its
classes need no `using module`) and writes one Markdown page per exported function under
docs/src/content/docs/reference/, grouped like the Proxmox VE API, plus an index page per group and
src/data/cmdlets.json (cmdlet name -> page, used by the redirects of the old site).

The pages are not committed: npm runs this script before `dev` and `build` (`predev`, `prebuild`),
locally and in the docs workflow, so the reference always matches the module. Everything under
reference/ is overwritten.

.EXAMPLE
pwsh -NoProfile -File docs/scripts/Update-CmdletReference.ps1
#>

$lines.Add('')
$lines.Add('Shorter names for common cmdlets, defined by the module.')
$lines.Add('')
$lines.Add('| Alias | Cmdlet |')
$lines.Add('|---|---|')
$byName = @{}; $cmdlets | ForEach-Object { $byName[$_.Name] = $_ }
foreach ($target in ($aliases.Keys | Sort-Object)) {
    foreach ($a in $aliases[$target]) {
        $link = $byName.ContainsKey($target) ? "[$target]($(Get-Url $byName[$target]))" : "``$target``"
        $lines.Add("| ``$a`` | $link |")
    }
}
Write-Utf8File (Join-Path $outDir 'index.md') $lines

# cmdlet -> page, for the redirects of the old MkDocs pages (markdown/<Cmdlet>.html).
$map = [ordered]@{}
$cmdlets | Sort-Object Name | ForEach-Object { $map[$_.Name] = "reference/$($_.Group)/$(Get-Slug $_.Name)/" }
# Old pages of names that are now aliases (Get-PveVm -> Get-PveGuest): the page of the function.
foreach ($target in $aliases.Keys) {
    $page = $map[$target]
    if ($page) { foreach ($a in $aliases[$target]) { if (-not $map.Contains($a)) { $map[$a] = $page } } }
}
# The old site also had pages for the internal helpers: send them to the module functions.
$internal | ForEach-Object { if (-not $map.Contains($_)) { $map[$_] = 'reference/module/' } }
Write-Utf8File $dataFile @(($map | ConvertTo-Json))

Write-Host "Written $($cmdlets.Count) cmdlet pages and $($folders.Count + 1) index pages to $outDir"

#region helpers
function Write-Utf8File([string]$Path, [string[]]$Lines) {
    $dir = Split-Path $Path -Parent
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    [IO.File]::WriteAllText($Path, (($Lines -join "`n").TrimEnd() + "`n"), [Text.UTF8Encoding]::new($false))
}

# The generator writes ':' as "':'" and '[' as '\[' in the comment-based help; undo it.
function Get-CleanText([string]$Text) {
    if ([string]::IsNullOrWhiteSpace($Text)) { return '' }
    $t = $Text.Replace("':'", ':').Replace('\[', '[')
    $t = ($t -split "`r?`n" | ForEach-Object { $_.Trim() }) -join ' '
    $t = $t -replace ' {2,}', ' '
    if ($t.Trim() -eq '--') { return '' }
    return $t.Trim()
}

# Plain Markdown: HTML special characters as entities, so '<GUEST>' is shown and not taken as a tag.
function ConvertTo-MdText([string]$Text) {
    return $Text.Replace('&', '&amp;').Replace('<', '&lt;').Replace('>', '&gt;')
}

function ConvertTo-MdCell([string]$Text) {
    return (ConvertTo-MdText $Text).Replace('|', '\|')
}

function ConvertTo-YamlString([string]$Text) {
    return "'" + $Text.Replace("'", "''") + "'"
}

function Get-FirstSentence([string]$Text) {
    if (-not $Text) { return '' }
    $m = [regex]::Match($Text, '^(.+?\.)(\s|$)')
    $s = $m.Success ? $m.Groups[1].Value : $Text
    return $s.Length -gt 160 ? $s.Substring(0, 157).TrimEnd() + '...' : $s
}

function Get-HelpText($Dictionary, [string]$Key) {
    if ($null -eq $Dictionary) { return '' }
    foreach ($k in $Dictionary.Keys) { if ($k -ieq $Key) { return $Dictionary[$k] } }
    return ''
}

function Get-Slug([string]$Name) { return $Name.ToLowerInvariant() }

# Comment-based help of a function: the first <# … #> block in its text. Parsed here because
# FunctionDefinitionAst.GetHelpContent() takes about 250 ms per function on this file.
function Get-CommentHelp([string]$FunctionText) {
    $help = @{ Synopsis = ''; Description = ''; Outputs = ''; Parameters = @{}; Examples = [System.Collections.Generic.List[string]]::new() }
    $m = [regex]::Match($FunctionText, '<#(.*?)#>', 'Singleline')
    if (-not $m.Success) { return $help }
    $section = $null; $arg = $null; $buffer = [System.Collections.Generic.List[string]]::new()
    $flush = {
        $text = ($buffer -join "`n").Trim()
        switch ($section) {
            'SYNOPSIS' { $help.Synopsis = $text }
            'DESCRIPTION' { $help.Description = $text }
            'OUTPUTS' { $help.Outputs = $text }
            'PARAMETER' { $help.Parameters[$arg] = $text }
            'EXAMPLE' { $help.Examples.Add($text) }
        }
        $buffer.Clear()
    }
    foreach ($line in ($m.Groups[1].Value -split "`r?`n")) {
        $k = [regex]::Match($line, '^\s*\.([A-Za-z]+)\s*(\S*)\s*$')
        if ($k.Success) {
            & $flush
            $section = $k.Groups[1].Value.ToUpperInvariant(); $arg = $k.Groups[2].Value
        }
        else { $buffer.Add($line) }
    }
    & $flush
    return $help
}

function Format-CodeList([string[]]$Items) { return ($Items | ForEach-Object { '`' + $_ + '`' }) -join ', ' }

# '$FabricId' -> '{fabric_id}': the generator title-cases the API name and drops '_' and '-', so an
# inner capital marks a separator: '_' for every path parameter of the current module (checked
# against the Proxmox VE apidoc.js).
# The generator leaves API names with '-' unreplaced, as literal placeholders with '_'
# ("/cluster/sdn/route-maps/entries/{route_map_id}"): shown here with the API's own name.
$literalPlaceholders = @{ '{route_map_id}' = '{route-map-id}'; '{pci_id_or_mapping}' = '{pci-id-or-mapping}' }
function ConvertTo-ApiPath([string]$Resource) {
    $path = [regex]::Replace($Resource, '\$([A-Za-z0-9_]+)', {
            param($m)
            $n = $m.Groups[1].Value.TrimEnd('_')
            '{' + ([regex]::Replace($n, '(?<=[a-z0-9])([A-Z])', '_$1')).ToLowerInvariant() + '}'
        })
    foreach ($k in $literalPlaceholders.Keys) { $path = $path.Replace($k, $literalPlaceholders[$k]) }
    return $path
}

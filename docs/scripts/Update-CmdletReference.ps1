#region parse
$tokens = $null
$errors = $null
$ast = [System.Management.Automation.Language.Parser]::ParseFile($psm1, [ref]$tokens, [ref]$errors)
if ($errors.Count -gt 0) { throw "Parse errors in ${psm1}: $($errors[0].Message)" }

$markerLine = (Select-String -Path $psm1 -Pattern ([regex]::Escape($generatedMarker)) | Select-Object -First 1).LineNumber
if (-not $markerLine) { throw "Marker '$generatedMarker' not found in $psm1" }

$exported = (Import-PowerShellDataFile $psd1).FunctionsToExport

# Aliases: Set-Alias -Name X -Value Y
$aliases = @{}
$ast.FindAll({ param($n) $n -is [System.Management.Automation.Language.CommandAst] -and $n.GetCommandName() -eq 'Set-Alias' }, $false) |
    ForEach-Object {
        $e = $_.CommandElements
        $name = $null; $value = $null
        for ($i = 1; $i -lt $e.Count - 1; $i++) {
            if ($e[$i] -is [System.Management.Automation.Language.CommandParameterAst]) {
                if ($e[$i].ParameterName -eq 'Name') { $name = $e[$i + 1].Value }
                elseif ($e[$i].ParameterName -eq 'Value') { $value = $e[$i + 1].Value }
            }
        }
        if ($name -and $value) {
            if (-not $aliases.ContainsKey($value)) { $aliases[$value] = [System.Collections.Generic.SortedSet[string]]::new() }
            [void]$aliases[$value].Add($name)
        }
    }

$functions = $ast.FindAll({ param($n) $n -is [System.Management.Automation.Language.FunctionDefinitionAst] }, $false) |
    Where-Object { $exported -contains $_.Name -and $internal -notcontains $_.Name }

$cmdlets = foreach ($fn in $functions) {
    $help = Get-CommentHelp $fn.Extent.Text
    $handWritten = $fn.Extent.StartLineNumber -lt $markerLine

    $parameters = foreach ($p in $fn.Body.ParamBlock.Parameters) {
        $name = $p.Name.VariablePath.UserPath
        $type = ($p.Attributes | Where-Object { $_ -is [System.Management.Automation.Language.TypeConstraintAst] } |
            Select-Object -First 1).TypeName.Name
        $paramAttr = $p.Attributes | Where-Object {
            $_ -is [System.Management.Automation.Language.AttributeAst] -and $_.TypeName.Name -eq 'Parameter'
        } | Select-Object -First 1
        $named = @($paramAttr ? $paramAttr.NamedArguments : @())
        $validateSet = $p.Attributes | Where-Object {
            $_ -is [System.Management.Automation.Language.AttributeAst] -and $_.TypeName.Name -eq 'ValidateSet'
        } | Select-Object -First 1

        $description = Get-CleanText (Get-HelpText $help.Parameters $name)
        # The generator appends the allowed values; they are shown from ValidateSet instead.
        $description = ($description -replace '\s*Enum: \S+$', '').Trim()

        [pscustomobject]@{
            Name         = $name
            Type         = $type ?? 'object'
            Mandatory    = [bool]($named | Where-Object ArgumentName -eq 'Mandatory')
            Pipeline     = [bool]($named | Where-Object ArgumentName -eq 'ValueFromPipeline')
            ByProperty   = [bool]($named | Where-Object ArgumentName -eq 'ValueFromPipelineByPropertyName')
            Values       = @($validateSet ? ($validateSet.PositionalArguments | ForEach-Object { $_.Value } | Where-Object { $_ -ne '' }) : @())
            Default      = $p.DefaultValue ? $p.DefaultValue.Extent.Text : ''
            Description  = $description
        }
    }

    $method = $null; $path = $null
    if (-not $handWritten) {
        $call = $fn.Body.Find({ param($n) $n -is [System.Management.Automation.Language.CommandAst] -and $n.GetCommandName() -eq 'Invoke-PveRestApi' }, $true)
        $e = $call.CommandElements
        for ($i = 1; $i -lt $e.Count - 1; $i++) {
            if ($e[$i] -is [System.Management.Automation.Language.CommandParameterAst]) {
                if ($e[$i].ParameterName -eq 'Method') { $method = $httpMethods[$e[$i + 1].Value] }
                elseif ($e[$i].ParameterName -eq 'Resource') { $path = ConvertTo-ApiPath $e[$i + 1].Value }
            }
        }
        if (-not $method -or -not $path) { throw "No Invoke-PveRestApi call found in $($fn.Name)" }
    }

    [pscustomobject]@{
        Name        = $fn.Name
        HandWritten = $handWritten
        Description = Get-CleanText ($help.Description ? $help.Description : $help.Synopsis)
        Outputs     = Get-CleanText (@($help.Outputs) -join ' ')
        Examples    = @($help.Examples)
        Parameters  = @($parameters)
        Method      = $method
        Path        = $path
        Aliases     = @($aliases.ContainsKey($fn.Name) ? $aliases[$fn.Name] : @())
        Group       = $null
    }
}
#endregion

#region groups
# Group like the API: first path segment; cluster and nodes one level deeper
# (/cluster/<group>/…, /nodes/{node}/<group>/…).
foreach ($c in $cmdlets) {
    if ($c.HandWritten) { $c.Group = 'module'; continue }
    $seg = @($c.Path.Trim('/').Split('/'))
    $c.Group = switch ($seg[0]) {
        'cluster' { $seg.Count -ge 2 ? "cluster/$($seg[1])" : 'cluster/general' }
        'nodes' { $seg.Count -ge 3 ? "nodes/$($seg[2])" : 'nodes/general' }
        default { $seg[0] }
    }
}
foreach ($parent in 'cluster', 'nodes') {
    $cmdlets | Where-Object { $_.Group -like "$parent/*" } | Group-Object Group |
        Where-Object Count -lt $minGroupSize | ForEach-Object { $_.Group | ForEach-Object { $_.Group = "$parent/general" } }
}

$groupInfo = [ordered]@{
    'module'  = 'Functions written by hand in the module: connection, raw API, tasks, VMs by id or name, snapshots.'
    'access'  = '/access — users, groups, roles, ACL, realms, API tokens, two-factor authentication.'
    'cluster' = '/cluster — cluster-wide configuration: SDN, firewall, notifications, HA, mappings, ACME, backup jobs, replication.'
    'nodes'   = '/nodes — everything on a node: VMs (qemu), containers (lxc), Ceph, storage, disks, network, services, tasks.'
    'pools'   = '/pools — resource pools.'
    'storage' = '/storage — storage definitions of the datacenter.'
    'version' = '/version — Proxmox VE version.'
}
$unknown = $cmdlets.Group | ForEach-Object { $_.Split('/')[0] } | Sort-Object -Unique | Where-Object { -not $groupInfo.Contains($_) }
if ($unknown) { throw "Top-level API groups without a description: $($unknown -join ', ')" }
#endregion

#region write
function Get-Url($c) { "$base/reference/$($c.Group)/$(Get-Slug $c.Name)/" }

function Get-Syntax($c) {
    $parts = foreach ($p in $c.Parameters) {
        $arg = $p.Type -eq 'switch' ? "-$($p.Name)" : "-$($p.Name) <$($p.Type)>"
        $p.Mandatory ? $arg : "[$arg]"
    }
    # One parameter per line: readable without scrolling sideways.
    return (@($c.Name) + ($parts + '[<CommonParameters>]' | ForEach-Object { "    $_" })) -join "`n"
}

if (Test-Path $outDir) { Remove-Item $outDir -Recurse -Force }

foreach ($c in $cmdlets) {
    $lines = [System.Collections.Generic.List[string]]::new()
    $summary = Get-FirstSentence $c.Description
    $lines.Add('---')
    $lines.Add("title: $($c.Name)")
    $lines.Add("description: $(ConvertTo-YamlString ($summary ? $summary : "$($c.Name) cmdlet of Corsinvest.ProxmoxVE.Api."))")
    $lines.Add('editUrl: false')
    $lines.Add('---')
    $lines.Add('')
    $lines.Add('<!-- Generated by docs/scripts/Update-CmdletReference.ps1 from the module source: do not edit. -->')
    $lines.Add('')
    if ($c.Description) { $lines.Add((ConvertTo-MdText $c.Description)); $lines.Add('') }

    if ($c.Path) {
        $lines.Add("**API:** ``$($c.Method) $($c.Path)`` — [Proxmox VE API viewer]($apiViewer$($c.Path))")
        $lines.Add('')
    }
    elseif ($guides.Contains($c.Name)) {
        $lines.Add("Explained with examples in [this guide]($base/$($guides[$c.Name])).")
        $lines.Add('')
    }
    if ($c.Aliases.Count) {
        $lines.Add("**Aliases:** $(Format-CodeList $c.Aliases)")
        $lines.Add('')
    }

    $lines.Add('## Syntax')
    $lines.Add('')
    $lines.Add('```powershell')
    $lines.Add((Get-Syntax $c))
    $lines.Add('```')
    $lines.Add('')

    if ($c.Parameters.Count) {
        $lines.Add('## Parameters')
        $lines.Add('')
        if ($c.HandWritten) {
            $lines.Add('| Parameter | Type | Required | Pipeline | Description |')
            $lines.Add('|---|---|---|---|---|')
        }
        else {
            $lines.Add('| Parameter | Type | Required | Description |')
            $lines.Add('|---|---|---|---|')
        }
        foreach ($p in $c.Parameters) {
            $desc = ConvertTo-MdCell $p.Description
            if ($desc -and $desc -notmatch '[.!?:)]$') { $desc += '.' }
            if ($p.Values.Count) { $desc = ($desc ? "$desc " : '') + "Values: $(Format-CodeList $p.Values)." }
            if ($p.Default -and $p.Type -ne 'switch') { $desc = ($desc ? "$desc " : '') + "Default: ``$($p.Default)``." }
            $row = "| ``-$($p.Name)`` | ``$($p.Type)`` | $($p.Mandatory ? 'Yes' : 'No') |"
            if ($c.HandWritten) {
                $pipe = $p.Pipeline ? 'By value, by property name' : ($p.ByProperty ? 'By property name' : 'No')
                $row += " $pipe |"
            }
            $lines.Add("$row $desc |")
        }
        $lines.Add('')
        if (-not $c.HandWritten) {
            $lines.Add("Every parameter also binds by property name from the pipeline, so an object with ``node`` and ``vmid`` properties — the output of [Get-PveGuest]($base/reference/module/get-pveguest/), for one — fills ``-Node`` and ``-Vmid``. Without ``-PveTicket`` the cmdlet uses the last connection, see [Connection]($base/connection/#the-last-connection).")
            $lines.Add('')
        }
    }

    $lines.Add('## Output')
    $lines.Add('')
    if ($c.HandWritten) {
        $lines.Add($c.Outputs ? (ConvertTo-MdText $c.Outputs) : 'Not documented in the module.')
    }
    else {
        $lines.Add("A ``PveResponse``: the data returned by Proxmox VE is in ``.Response.data``, the outcome in ``.IsSuccessStatusCode`` — see [Results]($base/concepts/results/) and [Errors]($base/concepts/errors/).")
    }
    $lines.Add('')

    if ($c.HandWritten -and $c.Examples.Count) {
        $lines.Add('## Example')
        $lines.Add('')
        foreach ($ex in $c.Examples) {
            $lines.Add('```powershell')
            $lines.Add(($ex.Trim() -replace "`r", ''))
            $lines.Add('```')
            $lines.Add('')
        }
    }

    Write-Utf8File (Join-Path $outDir "$($c.Group)/$(Get-Slug $c.Name).md") $lines
}

# One index per group folder, with the table of its cmdlets.
$folders = $cmdlets.Group | ForEach-Object {
    $_
    if ($_ -like '*/*') { $_.Split('/')[0] }
} | Sort-Object -Unique

foreach ($folder in $folders) {
    $inFolder = @($cmdlets | Where-Object { $_.Group -eq $folder -or $_.Group -like "$folder/*" } | Sort-Object Name)
    $top = $folder.Split('/')[0]
    $isTop = $folder -notlike '*/*'
    $title = $folder -eq 'module' ? 'Module functions' : ($isTop ? "/$folder" : "/$top/…/$($folder.Split('/')[1])")
    $desc = $isTop ? $groupInfo[$top] : "Cmdlets for $(($inFolder | Select-Object -First 1).Path -replace '^(/nodes/\{node\}|/cluster)/([^/]+).*$', '$1/$2') and below."
    if ($folder -like '*/general') { $desc = "Cmdlets of /$top that do not belong to a larger group." }

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add('---')
    $lines.Add("title: $(ConvertTo-YamlString $title)")
    $lines.Add("description: $(ConvertTo-YamlString "$desc ($($inFolder.Count) cmdlets)")")
    $lines.Add('editUrl: false')
    $lines.Add('sidebar:')
    $lines.Add('  label: Overview')
    $lines.Add('  order: 0')
    $lines.Add('---')
    $lines.Add('')
    $lines.Add('<!-- Generated by docs/scripts/Update-CmdletReference.ps1 from the module source: do not edit. -->')
    $lines.Add('')
    $lines.Add("$(ConvertTo-MdText $desc) $($inFolder.Count) cmdlets.")
    $lines.Add('')
    if ($folder -eq 'module') {
        $lines.Add('| Cmdlet | Description |')
        $lines.Add('|---|---|')
        foreach ($c in $inFolder) { $lines.Add("| [$($c.Name)]($(Get-Url $c)) | $(ConvertTo-MdCell (Get-FirstSentence $c.Description)) |") }
    }
    else {
        # A list, not a table: endpoints and cmdlet names are long and would not fit side by side.
        foreach ($c in ($inFolder | Sort-Object Path, Method)) {
            $desc = Get-FirstSentence $c.Description
            $lines.Add("- [$($c.Name)]($(Get-Url $c)) — ``$($c.Method) $($c.Path)``$($desc ? '<br>' + (ConvertTo-MdText $desc) : '')")
        }
    }
    Write-Utf8File (Join-Path $outDir "$folder/index.md") $lines
}

